// Builds assets/reward_campaign.json and assets/stamina_campaign.json from the global client's own
// master tables (see scripts/cdn_master.cjs).
//
//   node scripts/gen_campaigns.cjs
//
// master/campaign/reward_campaign (one row per campaign, 11 columns; layout from the Chinese fork's
// src/content/converters/reward-campaign.ts, which follows the decompiled client's
// RewardCampaignValues):
//   0 repeat (0 once, 1 weekly), 1 start, 2 end (UTC, like the other master dates), 3 weekday,
//   4 reset time (weekly only), 5 reward kind (0 items, 1 EXP, 2 mana), 6 rate,
//   7 quest range kind, 8..10 the range's queries (see questInRange in src/lib/mission.ts)
// master/campaign/stamina_campaign: the same without the reward kind (10 columns):
//   0 repeat, 1 start, 2 end, 3 weekday, 4 reset time, 5 stamina rate, 6 quest range kind, 7..9 queries
//
// Every row in the global data is a one-time campaign; weekly rows are kept but marked so the server
// can skip them rather than guess their schedule.

const path = require("path")
const fs = require("fs")
const { ROOT, readTable, parseCsvLine, empty } = require("./cdn_master.cjs")

// a blank or "(None)" query means "any"
const query = v => empty(v) ? null : v

function rows(table, columns, name) {
    return Object.entries(table).map(([id, line]) => {
        const c = parseCsvLine(line)
        if (c.length !== columns) throw new Error(`${name} ${id}: expected ${columns} columns, got ${c.length}.`)
        return [Number(id), c]
    }).sort((a, b) => a[0] - b[0])
}

;(async () => {
    const reward = rows(await readTable("master/campaign/reward_campaign.orderedmap"), 11, "reward_campaign")
    const rewardOut = reward.map(([id, c]) => {
        const rate = Number(c[6]), kind = Number(c[5])
        if (!(rate >= 1 && rate <= 10) || ![0, 1, 2].includes(kind)) throw new Error(`reward_campaign ${id}: odd rate or kind.`)
        return {
            id, weekly: c[0] === "1", start: c[1], end: c[2],
            rewardKind: kind, rate,
            range: [Number(c[7]), query(c[8]), query(c[9]), query(c[10])],
        }
    })
    const stamina = rows(await readTable("master/campaign/stamina_campaign.orderedmap"), 10, "stamina_campaign")
    const staminaOut = stamina.map(([id, c]) => {
        const rate = Number(c[5])
        if (!(rate >= 0 && rate <= 1)) throw new Error(`stamina_campaign ${id}: odd rate.`)
        return {
            id, weekly: c[0] === "1", start: c[1], end: c[2], rate,
            range: [Number(c[6]), query(c[7]), query(c[8]), query(c[9])],
        }
    })
    const note = "Generated by scripts/gen_campaigns.cjs from the global CDN master tables. Dates are UTC. range: [quest range kind, query 1, query 2, query 3] (questInRange in src/lib/mission.ts)."
    fs.writeFileSync(path.join(ROOT, "assets", "reward_campaign.json"), JSON.stringify({ _note: note, rewardKinds: { 0: "items", 1: "EXP", 2: "mana" }, campaigns: rewardOut }, null, 1))
    fs.writeFileSync(path.join(ROOT, "assets", "stamina_campaign.json"), JSON.stringify({ _note: note, campaigns: staminaOut }, null, 1))
    console.log(`reward_campaign.json: ${rewardOut.length} campaigns; stamina_campaign.json: ${staminaOut.length} campaigns`)
})()
